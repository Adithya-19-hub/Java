public class TwoDarray {
    public static void main(String args[]) {
        // 2-D array's
        int[][] array = new int[2][3];
        array[0][0] = 100;
        array[0][1] = 200;
        array[0][2] = 300;
        array[1][0] = 400;
        array[1][1] = 500;
        array[1][2] = 600;
        System.out.println(array[0][0]);

        System.out.println(array[0][1]);
        System.out.println(array[0][2]);
    }
}
